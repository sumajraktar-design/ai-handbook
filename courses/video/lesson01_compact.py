RATE = 4.6     # 朗读语速：字/秒（不含标点）
COMMA = 0.12   # 句中每个标点的停顿
GAP = 0.25     # 两条字幕之间的空隙
PRE, POST, POST_LAST = 0.35, 0.6, 2.0

PUNCT = r'[，。、：；？！,.:;?!"“”（）()\s…—·/%]'


def speak_dur(s):
    n = len(re.sub(PUNCT, '', s))
    k = len(re.findall(r'[，。、：；？！]', s.rstrip('。？！…')))
    return max(1.4, n / RATE + COMMA * k + 0.15)


for (i, j), s in EDITS.items():
    caps = list(m.SHOTS[i - 1]['captions'])
    caps[j] = s
    m.SHOTS[i - 1]['captions'] = caps


def anim_end(fn, cues):
    """动画里写死的 c[k] + x，取最晚的那个，保证镜头不会在动画结束前切走。"""
    src = inspect.getsource(fn)
    ends = [cues[int(k)] + float(x) for k, x in re.findall(r'c\[(\d)\]\s*\+\s*([\d.]+)', src) if int(k) < len(cues)]
    return max(ends, default=0) + 0.4


def build():
    out, prev_card = [], None
    for n, sh in enumerate(m.SHOTS):
        cues, ends, cur = [], [], PRE
        for s_ in sh['captions']:
            cues.append(cur)
            d = speak_dur(s_)
            ends.append(cur + d)
            cur += d + GAP
        post = POST_LAST if n == len(m.SHOTS) - 1 else POST
        total = max(min(sh['min_dur'], 5.0), cur - GAP + post, anim_end(sh['fn'], cues))
        cd = sh['card']
        if cd == 'keep':
            info, appear = prev_card, None
        elif cd:
            info, appear = cd, cues[sh['card_cue']]
        else:
            info, appear = None, None
        prev_card = info
        out.append(dict(sh, cues=cues, ends=ends, dur=total, card_info=info, card_at=appear))
    return out


m.build = build

if __name__ == '__main__':
    m.main()
